import express, { type RequestHandler } from 'express';
import { copyFile, mkdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

/**
 * Where uploaded files live. Local disk for now; an S3 or Cloudinary version only
 * has to implement this interface. Keys look like `events/<id>-<random>.webp`.
 */
export interface StorageService {
  put(key: string, data: Buffer, contentType: string): Promise<void>;
  copy(fromKey: string, toKey: string): Promise<void>;
  /** Deleting a missing key is not an error. */
  delete(key: string): Promise<void>;
  /** Public URL the browser loads the file from. */
  url(key: string): string;
  /** Serves files at PUBLIC_PATH, for storage that lives on this server. */
  serve?: RequestHandler;
}

export const UPLOADS_PUBLIC_PATH = '/api/uploads';

const KEY_PATTERN = /^[a-z0-9-]+\/[a-zA-Z0-9_-]+\.(jpg|png|webp)$/;

function assertKey(key: string) {
  // Keys are generated by us, but never let one escape the uploads directory.
  if (!KEY_PATTERN.test(key)) throw new Error(`Invalid storage key: ${key}`);
}

export function localDiskStorage(dir: string): StorageService {
  const root = path.resolve(dir);
  const file = (key: string) => {
    assertKey(key);
    return path.join(root, key);
  };

  return {
    async put(key, data) {
      await mkdir(path.dirname(file(key)), { recursive: true });
      await writeFile(file(key), data);
    },
    async copy(fromKey, toKey) {
      await mkdir(path.dirname(file(toKey)), { recursive: true });
      await copyFile(file(fromKey), file(toKey));
    },
    async delete(key) {
      await rm(file(key), { force: true });
    },
    url: (key) => `${UPLOADS_PUBLIC_PATH}/${key}`,
    // Keys are unique per upload, so files can be cached forever.
    serve: express.static(root, { immutable: true, maxAge: '1y', index: false, dotfiles: 'deny' }),
  };
}

/** In-memory storage for tests. */
export function memoryStorage() {
  const files = new Map<string, { data: Buffer; contentType: string }>();
  const storage: StorageService = {
    async put(key, data, contentType) {
      assertKey(key);
      files.set(key, { data, contentType });
    },
    async copy(fromKey, toKey) {
      const f = files.get(fromKey);
      if (f) files.set(toKey, f);
    },
    async delete(key) {
      files.delete(key);
    },
    url: (key) => `${UPLOADS_PUBLIC_PATH}/${key}`,
  };
  return Object.assign(storage, { files });
}
